import { ISSUE_TYPE_LABEL, type IssueType } from './shared';

/**
 * 错误的细分类。模型给的分类名不稳定（"时态"、"动词时态"、"主语与时态"说的是一回事），
 * 统计时按这里的关键词归并到固定的名字。顺序有意义：一个名字里出现多个关键词时，
 * 排在前面的优先，所以"主语与时态"和"时态与主语"都会归到"时态"。
 */
const RULES: [name: string, keywords: string[]][] = [
  ['时态', ['时态', '过去式', '过去时', '现在时', '将来时', '完成时', '进行时', '过去分词']],
  ['主谓一致', ['主谓', '第三人称', '三单']],
  ['冠词', ['冠词']],
  ['单复数', ['单复数', '复数', '可数']],
  ['介词', ['介词']],
  ['非谓语', ['不定式', '动名词', '非谓语', '分词']],
  ['比较级', ['比较级', '最高级']],
  ['情态动词', ['情态']],
  ['被动语态', ['被动', '语态']],
  ['从句', ['从句']],
  ['代词', ['代词']],
  ['连词', ['连词', '连接词']],
  ['语序', ['语序', '词序']],
  ['搭配', ['搭配', '固定用法', '习惯用法', '短语']],
  ['词性', ['词性', '形容词', '副词', '名词', '动词']],
  ['句子结构', ['句子结构', '句子成分', '主语', '谓语', '宾语', '缺少', '结构']],
  ['中文替代', ['中文']],
  ['中式英语', ['中式']],
  ['大小写', ['大小写', '大写', '小写']],
  ['拼写', ['拼写']],
  ['标点', ['标点', '逗号', '句号', '引号']],
  ['用词', ['用词', '选词', '词义', '措辞']],
  ['不够地道', ['地道', '自然', '口语']],
];

/** 给模型看的推荐分类名 */
export const CATEGORY_NAMES = RULES.map(([name]) => name);

export function normalizeCategory(type: IssueType, category: string | undefined) {
  const raw = (category ?? '').replace(/\s+/g, '');
  if (type === 'chinese') return '中文替代';
  if (!raw) return ISSUE_TYPE_LABEL[type] ?? '其他';
  for (const [name, keywords] of RULES) {
    if (keywords.some((k) => raw.includes(k))) return name;
  }
  return raw;
}
